// Generates src/lessons/curriculum.generated.ts (ids and titles only) from the stage files.
import { readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';

const dir = join(process.cwd(), 'src/lessons/stages');
const files = readdirSync(dir).filter((f) => /^stage-\d\d-.*\.ts$/.test(f)).sort();
const meta = [];
for (const f of files) {
  const mod = await import(pathToFileURL(join(dir, f)).href);
  const s = mod.default;
  const m = (l) => ({ id: l.id, title: l.title, kind: l.kind ?? 'lesson' });
  meta.push({ id: s.id, number: s.number, title: s.title, subtitle: s.subtitle, emoji: s.emoji, lessons: s.lessons.map(m), check: m(s.check), boss: m(s.boss) });
}
const out = `// GENERATED by scripts/gen-curriculum.ts — do not edit by hand. Run: npm run gen\nexport const CURRICULUM_DATA: unknown[] = ${JSON.stringify(meta, null, 2)};\n`;
writeFileSync(join(process.cwd(), 'src/lessons/curriculum.generated.ts'), out);
console.log(`curriculum: ${meta.length} stages, ${meta.reduce((n, s) => n + s.lessons.length + 2, 0)} lessons`);
