// One-off generator for mate-in-1 puzzles (writes src/content/matePuzzles.ts). Run: npx tsx scripts/gen-mates.ts
import { Chess } from 'chess.js';
import { writeFileSync } from 'node:fs';

let seed = 20240607;
const rnd = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};
const files = 'abcdefgh';
const sq = (i: number) => files[i % 8] + (Math.floor(i / 8) + 1);

interface Found { fen: string; uci: string; piece: string; san: string; n: number }
const found: Found[] = [];
const seen = new Set<string>();

for (let tries = 0; tries < 400000 && found.length < 200; tries++) {
  const squares = new Set<number>();
  const take = () => {
    let s = Math.floor(rnd() * 64);
    while (squares.has(s)) s = Math.floor(rnd() * 64);
    squares.add(s);
    return s;
  };
  const board: Record<string, string> = {};
  board[sq(take())] = 'K';
  board[sq(take())] = 'k';
  const white = ['Q', 'R', 'R', 'B', 'N', 'P', 'B', 'N'].sort(() => rnd() - 0.5).slice(0, 1 + Math.floor(rnd() * 3));
  white.forEach((p) => {
    const s = sq(take());
    if (p === 'P' && (s[1] === '1' || s[1] === '8')) return;
    board[s] = p;
  });
  const black = ['p', 'p', 'p', 'r', 'n', 'b'].sort(() => rnd() - 0.5).slice(0, Math.floor(rnd() * 4));
  black.forEach((p) => {
    const s = sq(take());
    if (p === 'p' && (s[1] === '1' || s[1] === '8')) return;
    board[s] = p;
  });
  const rows: string[] = [];
  for (let r = 8; r >= 1; r--) {
    let row = '';
    let e = 0;
    for (const f of files) {
      const p = board[f + r];
      if (!p) e++;
      else {
        if (e) row += e;
        e = 0;
        row += p;
      }
    }
    rows.push(row + (e || ''));
  }
  const fen = `${rows.join('/')} w - - 0 1`;
  let c: Chess;
  try {
    c = new Chess(fen);
  } catch {
    continue;
  }
  // legal position: the side NOT to move (Black) must not already be in check
  try {
    if (new Chess(fen.replace(' w ', ' b ')).isCheck()) continue;
  } catch {
    continue;
  }
  const mates = c.moves({ verbose: true }).filter((m) => {
    c.move(m);
    const ok = c.isCheckmate();
    c.undo();
    return ok;
  });
  if (mates.length !== 1) continue; // exactly one mating move: a clean puzzle
  const m = mates[0];
  if (m.promotion) continue;
  const key = `${m.piece}-${Object.keys(board).length}`;
  if (seen.has(fen)) continue;
  seen.add(fen);
  found.push({ fen, uci: m.from + m.to, piece: m.piece, san: m.san, n: Object.keys(board).length });
  void key;
}

// pick a varied set: prefer few pieces, mix of mating pieces
const byPiece: Record<string, Found[]> = {};
found.filter((f) => f.n <= 6).forEach((f) => (byPiece[f.piece] ??= []).push(f));
const order = ['q', 'r', 'r', 'q', 'b', 'n', 'r', 'q', 'p', 'k', 'b', 'n', 'r', 'q'];
const picked: Found[] = [];
for (const p of order) {
  const f = byPiece[p]?.shift();
  if (f) picked.push(f);
}
console.log(found.length, 'found;', picked.length, 'picked;', picked.map((f) => f.san).join(' '));
const body = picked.map((f) => `  { fen: '${f.fen}', answer: '${f.uci}', san: '${f.san}' },`).join('\n');
writeFileSync(
  'src/content/matePuzzles.ts',
  `// GENERATED by scripts/gen-mates.ts: positions where White has exactly one mating move.\nexport interface MatePuzzle { fen: string; answer: string; san: string }\nexport const MATE_PUZZLES: MatePuzzle[] = [\n${body}\n];\n`,
);
